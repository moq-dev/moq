#!/usr/bin/env bash
#
# Run the CARLA simulator on the local GPU, in podman.
#
# CARLA is distributed as an Unreal Engine build against Ubuntu's driver stack,
# so a container is the only sane way to run it on Fedora/NixOS. It renders
# offscreen and speaks its RPC on :2000; the worker (`just carla worker`) is a
# client and can be restarted independently.
set -euo pipefail

# Stock upstream by default. The worker needs the patched build (the GPU video
# bridge and the RPC work guard), a local image built by
# https://github.com/moq-dev/carla, so it is selected by pinning CARLA_IMAGE
# rather than shipped here; put
# that pin in ~/.config/moq/carla.env, which carla-sim.service reads. The
# resolved image is logged below, so a pin that went missing is visible. The
# worker refuses a stock simulator by name.
image="${CARLA_IMAGE:-docker.io/carlasim/carla:0.9.16}"
name="${CARLA_NAME:-carla}"
port="${CARLA_PORT:-2000}"
# Where the bridge inside the simulator listens for the worker; the worker's
# --bridge-socket defaults to the same path.
bridge_dir="${CARLA_BRIDGE_DIR:-${XDG_RUNTIME_DIR:-/tmp}/carla-bridge}"

if ! command -v podman >/dev/null 2>&1; then
    echo "carla: podman not found." >&2
    exit 1
fi

# The GPU reaches the container through a CDI device generated by
# nvidia-container-toolkit. Check its referenced entries and hook before pulling
# the 8.6 GB image: a spec generated through a bare `nix shell` embeds an
# unrooted store path that breaks after Nix GC even though the YAML still exists.
# nvidia-ctk writes YAML by default, while NixOS's declarative generator writes
# JSON. Accept both without depending on jq at service runtime.
if [[ -n "${CARLA_CDI_SPEC:-}" ]]; then
    specs=("$CARLA_CDI_SPEC")
else
    shopt -s nullglob
    specs=(/etc/cdi/*nvidia* /var/run/cdi/*nvidia* "${XDG_CONFIG_HOME:-$HOME/.config}"/cdi/*nvidia*)
    shopt -u nullglob
fi

valid_spec=
for spec in "${specs[@]}"; do
    valid=1
    entry_seen=0
    hook_seen=0
    while IFS= read -r host_path; do
        case "$host_path" in
            *nvidia-ctk | *nvidia-cdi-hook) ;;
            *) entry_seen=1 ;;
        esac
        if [[ ! -e "$host_path" ]]; then
            valid=0
            break
        fi
    done < <(sed -nE \
        -e 's/^[[:space:]]*(- )?(path|hostPath):[[:space:]]+([^[:space:]]+)[[:space:]]*$/\3/p' \
        -e 's/^[[:space:]]*"(path|hostPath)":[[:space:]]*"([^"]+)",?[[:space:]]*$/\2/p' \
        "$spec")
    while IFS= read -r hook; do
        hook_seen=1
        if [[ ! -x "$hook" ]]; then
            valid=0
            break
        fi
    done < <(sed -nE \
        -e 's/^[[:space:]]*(- )?path:[[:space:]]+([^[:space:]]*nvidia-(ctk|cdi-hook))[[:space:]]*$/\2/p' \
        -e 's/^[[:space:]]*"path":[[:space:]]*"([^"]*nvidia-(ctk|cdi-hook))",?[[:space:]]*$/\1/p' \
        "$spec")
    if [[ "$valid" -eq 1 && "$entry_seen" -eq 1 && "$hook_seen" -eq 1 ]]; then
        valid_spec="$spec"
        break
    fi
done

if [[ -z "$valid_spec" ]]; then
    cat >&2 <<-'EOF'
		carla: the nvidia.com/gpu CDI device is missing or stale. Set it up with:

		  just carla cdi

		Then point Podman at it by adding to ~/.config/containers/containers.conf:

		  [engine]
		  cdi_spec_dirs = ["/etc/cdi", "/var/run/cdi", "<your home>/.config/cdi"]
	EOF
    exit 1
fi

# Name the resolved image in the journal, so a pin that has quietly gone back
# to stock is visible rather than showing up only as idle CPU.
digest="$(podman image inspect --format '{{.Digest}}' "$image" 2>/dev/null || true)"
echo "carla: image $image (${digest:-not pulled yet})" >&2

# --security-opt label=disable: SELinux denies a container access to
# /dev/nvidia* even though the nodes are mode 0666, and the failure looks like a
# missing driver rather than a denial. The alternative is a host-wide
# `setsebool -P container_use_devices 1`, which needs root.
#
# --net=host: the worker connects to the RPC port and the traffic manager port,
# and CARLA hands out further ports at runtime.
#
# --userns=keep-id: the image's carla user is UID 1000, and keeping IDs makes
# it this user, so the bridge's socket in the shared directory is one the
# worker may connect to. The directory stays private to this user.
# The name is the service's ownership boundary. --replace lets systemd adopt a
# manually started or orphaned simulator container instead of retrying forever on a
# name collision; it never touches another container name.
#
# The engine binary directly, not the image's CarlaUE4.sh: that wrapper runs
# the binary without exec, leaving a shell as container PID 1 that ignores
# SIGTERM, so a stop would sit through systemd's timeout and leave the
# simulator running. As PID 1 the engine gets the signal and exits in a few
# seconds.
# Override the image entrypoint too: wrappers can silently append quality or
# experimental flags after the launcher's arguments.
mkdir -p "$bridge_dir"
chmod 700 "$bridge_dir"
exec podman run --rm --replace --name "$name" \
    --security-opt label=disable \
    --device nvidia.com/gpu=all \
    --net=host \
    --userns=keep-id \
    -v "$bridge_dir:$bridge_dir" \
    --entrypoint /workspace/CarlaUE4/Binaries/Linux/CarlaUE4-Linux-Shipping \
    "$image" \
    CarlaUE4 -RenderOffScreen -nosound -carla-rpc-port="$port" -quality-level=Epic \
    -moq-bridge-socket="$bridge_dir/bridge.sock"
