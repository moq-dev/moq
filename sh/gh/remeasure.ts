import { spawnSync } from "node:child_process";
import { appendFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

/** Whether a published package changed a pin in a planned break. */
export function changedPins(
	breaks: Record<string, { releases: Record<string, string> }>,
	releases: Record<string, string>,
) {
	return Object.values(breaks).some((entry) =>
		Object.entries(entry.releases).some(([pkg, version]) => {
			if (!releases[pkg]) throw new Error(`Unresolved planned-break package: ${pkg}`);
			return releases[pkg] !== version;
		}),
	);
}

function run(command: string, args: string[]) {
	const result = spawnSync(command, args, { stdio: "inherit" });
	if (result.error) throw result.error;
	if (result.status !== 0) throw new Error(`${command} failed: ${result.status ?? result.signal}`);
}

if (import.meta.main) {
	const directory = ".tmp/remeasure";
	mkdirSync(directory, { recursive: true });
	process.env.HARNESS_RUNS ??= resolve(directory, "runs");
	process.env.HARNESS_KEEP = "1";
	process.env.REMEASURE_REPORT = resolve(directory, "report.txt");
	let report = "Measurement skipped: published pins are unchanged.";
	const file = "test/interop/compat/planned-breaks.json";
	const before = readFileSync(file, "utf8");
	run("bun", ["test/interop/compat/resolve.ts", "resolve", `${directory}/versions.json`]);
	const releases = JSON.parse(readFileSync(`${directory}/versions.json`, "utf8"));
	if (process.env.REMEASURE_FORCE === "1" || changedPins(JSON.parse(before), releases)) {
		run("just", ["test", "wire-compat", "--remeasure"]);
		report = readFileSync(process.env.REMEASURE_REPORT, "utf8");
	}
	const changed = before !== readFileSync(file, "utf8");
	if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `changed=${changed}\n`);
	const url =
		process.env.GITHUB_ACTIONS === "true"
			? `${process.env.GITHUB_SERVER_URL}/${process.env.GITHUB_REPOSITORY}/actions/runs/${process.env.GITHUB_RUN_ID}`
			: "local run";
	writeFileSync(
		`${directory}/body.md`,
		`## Problem\n\nPublished packages changed the planned-break pins.\n\n## Approach\n\nRe-measured main against registry releases using \`just test wire-compat --remeasure\`. Kept only breaks that still fail, with the measured pins.\n\n## Impact\n\n- Public API and wire: none. Only compatibility expectations change.\n\n## Validation\n\nMeasurement and retained failure logs: ${url}. Unplanned failures abort the update.\n\n### Failing cells by planned break\n\n\`\`\`text\n${report.trimEnd()}\n\`\`\`\n\n## Alternatives\n\nManual remeasurement leaves scheduled Interop red between releases and pin updates.\n\n## Follow-ups\n\nNone.\n\nGenerated by the Release remeasure workflow.\n`,
	);
	console.log(changed ? "Measured pins changed" : "No planned-break diff");
}
